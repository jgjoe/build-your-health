-- Persistent account policy for both existing and nonexistent IDs; no MEMBER foreign key.
CREATE TABLE LOGIN_ATTEMPT (
    ACCOUNT_KEY       RAW(32) NOT NULL,
    FAILURE_COUNT     NUMBER(2) NOT NULL,
    WINDOW_STARTED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    LOCKED_UNTIL      TIMESTAMP(6) WITH TIME ZONE,
    EXPIRES_AT        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_LOGIN_ATTEMPT PRIMARY KEY (ACCOUNT_KEY),
    CONSTRAINT CK_LOGIN_ATTEMPT_COUNT CHECK (FAILURE_COUNT BETWEEN 1 AND 5)
);

CREATE INDEX IX_LOGIN_ATTEMPT_EXPIRY ON LOGIN_ATTEMPT(EXPIRES_AT);
